from transformers import pipeline
from datasets import load_dataset
import re
from pathlib import Path
import gc
import textwrap
import torch

N_PROBLEMS = 10

REQUIREMENTS = """
Requirements:
- Generate a complete C program with only the function that solve the problem.
- Print only the final result to stdout.
- Do not print explanations or debugging information.
- Return the solution inside a ```c code block.
"""

# Dedented before formatting, so the problem text doesn't break the dedent
PROMPT_TEMPLATES = [
    textwrap.dedent("""
        Solve the following LeetCode problem using C (not C++).
    """).strip() + "\n" + REQUIREMENTS + "\nProblem:\n{problem}",
    textwrap.dedent("""
        You are an expert C programmer, that knows how to make clean and optimized memory/processing code. Solve the following LeetCode problem using C (not C++).
    """).strip() + "\n" + REQUIREMENTS + "\nProblem:\n{problem}",
]

if __name__ == "__main__":
    # Leetcode problems dataset
    dataset = load_dataset(
        "newfacade/LeetCodeDataset",
        split="train"
    )

    df = dataset.to_pandas()
    df = df[df["difficulty"] == "Hard"]

    # Open source models in Hugging Face
    models = [
        # Heavy models (problematic)
        #"deepseek-ai/DeepSeek-V4.1-Flash-1017", # https://huggingface.co/deepseek-ai/DeepSeek-V4.1-Flash-1017
        #"openai/gpt-oss-20b", # https://huggingface.co/openai/gpt-oss-20b
        #"Qwen/Qwen3-Coder-30B-A3B-Instruct-FP8", # https://huggingface.co/Qwen/Qwen3-Coder-30B-A3B-Instruct-FP8

        # Light models
        "Qwen/Qwen2.5-Coder-1.5B-Instruct",
        "Qwen/Qwen2.5-Coder-3B-Instruct",
        "deepseek-ai/deepseek-coder-1.3b-instruct",
        "microsoft/Phi-4-mini-instruct",
        "HuggingFaceTB/SmolLM3-3B"
    ]

    # Runs
    for model in models:
        generator = pipeline(
            "text-generation",
            model=model,
            model_kwargs={
                "cache_dir": "./models"
            },
            device_map="auto"
        )

        counter = 0

        for row in df.itertuples():
            if counter == N_PROBLEMS: break

            counter += 1
            prompts = [template.format(problem=row.problem_description) for template in PROMPT_TEMPLATES]

            for idx, prompt in enumerate(prompts):
                messages = [{"role": "user", "content": prompt}]
                # SmolLM3 reasons by default, which can use up max_new_tokens
                if "SmolLM3" in model:
                    messages.insert(0, {"role": "system", "content": "/no_think"})

                response = generator(
                    messages,
                    max_new_tokens=2000,
                    do_sample=False, # Same prompt gives same code every run
                )
                generated_text = response[0]["generated_text"][-1]["content"]

                folder = Path("generated_code") / model.replace("/", "_")
                folder.mkdir(parents=True, exist_ok=True)

                # Raw response, to diagnose when no code is extracted
                #raw_file = folder / f"{row.question_id}_prompt{idx}.txt"
                #raw_file.write_text(generated_text, encoding="utf-8")

                match = re.search(
                    r"```c[^\S\n]*\n(.*?)```",
                    generated_text,
                    re.DOTALL | re.IGNORECASE
                )

                code = match.group(1) if match else None

                if not code:
                    print(f"No C code generated by {model} for problem {row.question_id} (prompt {idx})")
                    continue

                print(f"Saving {model} generated code for problem {row.question_id}")

                source_file = folder / f"{row.question_id}_prompt{idx}.c"
                source_file.write_text(code, encoding="utf-8")

        # Only delete the name
        del generator
        # Runs python's garbage collector (frees model's memory once nothing else references it)
        gc.collect()
        # Releases GPU memory
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
